from flask import Flask, jsonify, request
from flask_cors import CORS

from config import Config
from extensions import db, migrate, jwt, mail

from routes.assets import assets_bp
from routes.vendors import vendors_bp
from routes.assignments import assignments_bp
from routes.employees import employees_bp
from routes.dashboard import dashboard_bp
from routes.auth import auth_bp
from routes.users import users_bp
from routes.asset_requests import asset_requests_bp
from routes.employee_assets import employee_assets_bp
from routes.employee_dashboard import employee_dashboard_bp
from routes.audit_logs import audit_logs_bp
from routes.maintenance import maintenance_bp
from routes.qr_audits import qr_audits_bp
from routes.it_support import it_support_bp


def create_app():
    app = Flask(__name__)

    app.config.from_object(Config)
    
    app.register_blueprint(assets_bp)
    app.register_blueprint(vendors_bp)
    app.register_blueprint(assignments_bp)
    app.register_blueprint(employees_bp)
    app.register_blueprint(dashboard_bp)
    app.register_blueprint(auth_bp)
    app.register_blueprint(users_bp)
    app.register_blueprint(asset_requests_bp)
    app.register_blueprint(employee_assets_bp)
    app.register_blueprint(employee_dashboard_bp)
    app.register_blueprint(audit_logs_bp)
    app.register_blueprint(maintenance_bp)
    app.register_blueprint(qr_audits_bp)
    app.register_blueprint(it_support_bp)

    db.init_app(app)
    migrate.init_app(app, db)
    jwt.init_app(app)
    mail.init_app(app)

    CORS(
        app,
        resources={
            r"/api/*": {
            "origins": [
                r"http://localhost:\d+",
                r"http://127\.0\.0\.1:\d+",
                r"http://192\.168\.\d+\.\d+:\d+"
            ],
                "methods": [
                    "GET",
                    "POST",
                    "PUT",
                    "PATCH",
                    "DELETE",
                    "OPTIONS"
                ],
                "allow_headers": [
                    "Content-Type",
                    "Authorization"
                ],
                "supports_credentials": True
            }
        }
    )

    from models import (
        Employee, 
        Vendor, 
        Asset, 
        AssetAssignment, 
        User, 
        AuditLog, 
        AssetMaintenance, 
        AssetAuditSession, 
        AssetAuditScan, 
        ITRequest, 
        SupportTicket, 
        ITRequestHistory
    )

    # Central audit logging for successful state changes and authentication.
    # Never persist request bodies (they may contain passwords or tokens).
    @app.after_request
    def record_audit_event(response):
        path = request.path
        is_login = path == "/api/auth/login" and request.method == "POST"
        is_logout = path == "/api/auth/logout" and request.method == "POST"
        is_write = request.method in {"POST", "PUT", "PATCH", "DELETE"}

        if not path.startswith("/api/") or path.startswith("/api/audit-logs"):
            return response
        if not (is_login or is_logout or is_write):
            return response
        if response.status_code < 200 or response.status_code >= 300:
            return response

        try:
            from flask_jwt_extended import get_jwt
            # Login is intentionally public and has no verified JWT context.
            claims = {} if is_login else (get_jwt() or {})
            account_type = claims.get("account_type")
            account_id = claims.get("account_id")
            actor = None

            # Login has no bearer token yet; derive actor only from the successful
            # response generated by our own login endpoint.
            login_payload = {}
            if is_login:
                login_payload = response.get_json(silent=True) or {}
                if not login_payload.get("success") or not login_payload.get("user"):
                    return response
                login_user = login_payload["user"]
                account_type = login_payload.get("account_type")
                account_id = login_user.get("id")
                actor_name = login_user.get("name") or "Unknown"
                actor_email = login_user.get("email")
                actor_role = login_user.get("role") or account_type
            else:
                if account_id and account_type == "EMPLOYEE":
                    actor = db.session.get(Employee, int(account_id))
                elif account_id and account_type == "USER":
                    actor = db.session.get(User, int(account_id))
                if actor is None:
                    # Do not create unattributed business audit entries.
                    return response
                actor_name = getattr(actor, "name", None) or "Unknown"
                actor_email = getattr(actor, "email", None)
                actor_role = "EMPLOYEE" if account_type == "EMPLOYEE" else getattr(actor, "role", None)

            if is_login:
                action, entity_type, entity_id = "LOGIN", "AUTH", str(account_id)
                description = "Successful login"
            elif is_logout:
                action, entity_type, entity_id = "LOGOUT", "AUTH", str(account_id)
                description = "Successful logout"
            else:
                action_map = {"POST": "CREATE", "PUT": "UPDATE", "PATCH": "UPDATE", "DELETE": "DELETE"}
                action = action_map[request.method]
                low_path = path.lower()
                if "upload" in low_path:
                    action = "UPLOAD"
                elif "return" in low_path:
                    action = "RETURN"
                elif "assign" in low_path:
                    action = "ASSIGN"

                parts = [part for part in path.split("/") if part]
                resource = parts[1] if len(parts) > 1 else "system"
                entity_map = {
                    "assets": "ASSET", "employees": "EMPLOYEE", "vendors": "VENDOR",
                    "assignments": "ASSIGNMENT", "users": "USER", "asset-requests": "REQUEST",
                    "employee-assets": "ASSET", "auth": "PROFILE", "profile": "PROFILE",
                }
                entity_type = entity_map.get(resource, resource.replace("-", "_").rstrip("s").upper()[:80])
                entity_id = parts[2] if len(parts) > 2 else None
                if resource == "auth":
                    entity_type = "PROFILE"
                label = entity_type.replace("_", " ").lower()
                description = f"{action.title()} {label} via {path}"[:500]

            entry = AuditLog(
                actor_id=int(account_id) if account_id is not None else None,
                actor_type=account_type or "UNKNOWN",
                actor_name=actor_name[:150], actor_email=actor_email,
                actor_role=actor_role, action=action, entity_type=entity_type,
                entity_id=str(entity_id)[:100] if entity_id is not None else None,
                description=description[:500], method=request.method,
                endpoint=path[:255], status_code=response.status_code,
                ip_address=(request.headers.get("X-Forwarded-For", request.remote_addr) or "")[:64],
            )
            db.session.add(entry)
            db.session.commit()
        except Exception:
            db.session.rollback()
            app.logger.exception("Failed to write audit log")
        return response

    @app.route("/api/health")
    def health():
        return jsonify({
            "status": "success",
            "message": "Asset Management API is running"
        })

    return app


app = create_app()


if __name__ == "__main__":
    app.run(
        host="0.0.0.0",
        port=5000,
        debug=True
    )